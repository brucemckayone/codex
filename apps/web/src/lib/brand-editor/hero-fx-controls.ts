/**
 * The brand editor's controls for the hero's shader presets, as data: the
 * slider, colour and toggle each shader-* token is set with, in the order the
 * editor draws them. ControlField.svelte renders one; the hero effects and
 * combine levels lay them out. Every key is one of HERO_FX_DEFAULTS
 * (hero-fx-presets.ts), whose value is the control's default.
 */
import {
  FX_SETTINGS,
  type FxSetting,
  presetFxKey,
} from '$lib/components/ui/ShaderHero/preset-fx-defaults';
import type { LivePresetId } from '$lib/components/ui/ShaderHero/shader-config';

/** A range slider with formatted value display. */
export interface SliderControlConfig {
  kind: 'slider';
  /** Token override key (e.g. 'shader-curl'). Must exist in HERO_FX_DEFAULTS. */
  key: string;
  /** Visible label text. */
  label: string;
  min: number;
  max: number;
  step: number;
  /**
   * How to format the displayed value:
   *  - 'int':    String(Math.round(n))
   *  - 'fixed1': n.toFixed(1)
   *  - 'fixed2': n.toFixed(2)
   *  - 'fixed3': n.toFixed(3)
   *  - 'angle':  String(Math.round(n)) + '°'
   */
  format: 'int' | 'fixed1' | 'fixed2' | 'fixed3' | 'angle';
  minLabel?: string;
  maxLabel?: string;
}

/** Native HTML <input type="color">. */
export interface ColorControlConfig {
  kind: 'color';
  key: string;
  label: string;
}

/** Boolean toggle (stores '1'/'0' in the override bucket). */
export interface ToggleControlConfig {
  kind: 'toggle';
  key: string;
  label: string;
}

export type ControlConfig =
  | SliderControlConfig
  | ColorControlConfig
  | ToggleControlConfig;

