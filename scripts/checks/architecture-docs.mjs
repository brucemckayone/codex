/**
 * Renders docs/architecture/rules.md from the registry (G0 WP-4,
 * Codex-xtcfl.4). The page is generated, and the RULES-DOC rule fails when the
 * committed copy differs, because a rules page written by hand drifts: the
 * payments architecture doc said a money file was 5,097 lines long when it was
 * 9,015.
 *
 * Every heading here is a bare rule ID, so GitHub's anchor for it is the ID in
 * lower case, which is what the runner's messages link to.
 */
import { IGNORE_KEYWORD } from './architecture-ignores.mjs';
import { MATCHERS } from './architecture-matchers.mjs';

export const RULES_DOC = 'docs/architecture/rules.md';

const code = (s) => `\`${s}\``;

function scopeLines(rule) {
  const { include = ['**'], exclude = [] } = rule.scope ?? {};
  const lines = [`- **Applies to:** ${include.map(code).join(', ')}`];
  if (exclude.length)
    lines.push(`- **Except:** ${exclude.map(code).join(', ')}`);
  return lines;
}

function matchLine(rule) {
  const { kind, pattern, newFileMax, budgets, defaultBudget } = rule.match;
  const parts = [`${code(kind)}`];
  if (pattern instanceof RegExp) parts.push(`matching ${code(pattern.source)}`);
  if (newFileMax)
    parts.push(
      `a new or unpinned file may have up to ${newFileMax.toLocaleString('en-GB')} lines`
    );
  if (defaultBudget) {
    const named = Object.entries(budgets ?? {}).map(
      ([f, n]) => `${code(f)} ${n.toLocaleString('en-GB')}`
    );
    parts.push(
      `budget ${[...named, `every other ${defaultBudget.toLocaleString('en-GB')}`].join(', ')} words`
    );
  }
  if (MATCHERS[kind].unit)
    parts.push(
      `(measures ${MATCHERS[kind].unit}; the baseline pins larger files at their size)`
    );
  return `- **Checked by:** ${parts.join(', ')}`;
}

/**
 * @param {object[]} rules the registry's RULES
 * @param {object[]} gates the registry's GATES
 */
export function renderRulesDoc(rules, gates) {
  const out = [
    '# Architecture rules',
    '',
    '<!-- GENERATED by `pnpm check:arch --write-rules` from scripts/checks/architecture-rules.mjs. Do not edit by hand: the RULES-DOC rule fails when this page differs from the registry. -->',
    '',
    'Every rule on this page runs in CI and at commit time (`scripts/checks/check-architecture.mjs`). Debt that existed when a rule arrived is held in `scripts/checks/architecture-baseline.json`, as a count per rule and file, and a count may only fall.',
    '',
    '| ID | Rule |',
    '|---|---|',
    ...rules.map((r) => `| [${r.id}](#${r.id.toLowerCase()}) | ${r.title} |`),
    '',
    '## Adding a rule',
    '',
    'Pick the strongest **mechanism** first, then the strongest **channel** that can run it:',
    '',
    '1. **Architecture:** one owner and one way, so the wrong import cannot build.',
    '2. **Types:** an illegal state that does not compile.',
    '3. **A rule on this page:** its message names the one fix.',
    '4. **A test:** a fixture taken from a real past mistake.',
    '5. **Docs:** judgment calls only; nothing fails when an agent skips them.',
    '',
    'A rule here is one entry in `scripts/checks/architecture-rules.mjs`. The self-test fails unless the rule has a fixture that fires and names the past mistake it reproduces.',
    '',
    '## The baseline',
    '',
    '- A count above the baseline is a new violation, and fails.',
    '- A count below it also fails, until `pnpm check:arch --lower` banks the fix, so the headroom a fix frees cannot be spent by the next violation.',
    "- An entry for a file that is gone, or out of the rule's scope, fails until `--lower` removes it.",
    '- `--lower` only ever lowers or removes. Raising a count is a hand edit of the JSON, and needs a countersign (below).',
    '',
    '<a id="raises"></a>',
    '',
    '## Raising a count',
    '',
    'A raise loosens a gate, so in a pull request every raised or added baseline count needs its reason in the PR description, one line per entry. CI fails the PR without it:',
    '',
    '```text',
    'G0-RAISE: <RULE> <file> — <reason>',
    '```',
    '',
    '<a id="exceptions"></a>',
    '',
    '## Exceptions',
    '',
    'A single line can be excepted from a line-level rule by a comment on the line above it. The exception names one rule, an expiry date, the person who granted it and a reason:',
    '',
    '```ts',
    `// ${IGNORE_KEYWORD} A1 until=2026-12-31 by=<owner> — <reason>`,
    '```',
    '',
    'In markdown, use an HTML comment. The gate fails an exception that has expired, that excuses nothing, that is malformed, or that names a rule measuring a whole file (SIZE, DOC-BUDGET), whose exception is its baseline count.',
    '',
    '## Rules',
    '',
  ];
  for (const rule of rules) {
    out.push(
      `### ${rule.id}`,
      '',
      `**${rule.title}.**`,
      '',
      rule.why,
      '',
      ...scopeLines(rule),
      matchLine(rule),
      `- **Fix:** ${rule.fix}`,
      ''
    );
  }
  out.push(
    '## Other CI gates',
    '',
    "The static-analysis job runs these too. The CI-GATES rule keeps this list and the job's steps equal in both directions, and `pnpm check:arch --gates` runs each one locally (`gate.sh` calls it).",
    '',
    '| Gate | Checks | Runs |',
    '|---|---|---|',
    ...gates.map(
      (g) =>
        `| ${g.id} | ${g.title} | ${[g.selfTest, g.run, ...(g.prOnly ?? [])].filter(Boolean).map(code).join('<br>')} |`
    ),
    ''
  );
  return out.join('\n');
}
